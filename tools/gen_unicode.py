# Regenerates src/unicode_tables.inc from Python's unicodedata (Unicode Character Database).
# usage: python3 gen_unicode.py src/unicode_tables.inc
import unicodedata, sys
# Category codes matching .NET UnicodeCategory enum values
cats = {'Lu':0,'Ll':1,'Lt':2,'Lm':3,'Lo':4,'Mn':5,'Mc':6,'Me':7,'Nd':8,'Nl':9,'No':10,'Zs':11,'Zl':12,'Zp':13,'Cc':14,'Cf':15,'Cs':16,'Co':17,'Pc':18,'Pd':19,'Ps':20,'Pe':21,'Pi':22,'Pf':23,'Po':24,'Sm':25,'Sc':26,'Sk':27,'So':28,'Cn':29}
runs=[]
prev=None; start=0
for c in range(0x10000):
    cat = cats[unicodedata.category(chr(c))]
    if cat!=prev:
        if prev is not None: runs.append((start,prev))
        prev=cat; start=c
runs.append((start,prev))
lower=[]
for c in range(0x10000):
    ch=chr(c)
    if 0xD800<=c<=0xDFFF: continue
    l=ch.lower()
    if len(l)==1 and l!=ch: lower.append((c,ord(l)))
# .NET culture ToLower maps U+0130 to 'i' (non-Turkish cultures); Python gives 'i̇' (2 chars)
lower.append((0x130,0x69))
lower.sort()
with open(sys.argv[1],'w') as f:
    f.write('// This Source Code Form is subject to the terms of the Mozilla Public\n'
            '// License, v. 2.0. If a copy of the MPL was not distributed with this\n'
            '// file, You can obtain one at https://mozilla.org/MPL/2.0/.\n'
            '//\n'
            '// Generated by tools/gen_unicode.py from the Unicode Character Database %s (general categories +\n'
            '// simple lowercase mapping), BMP only. Unicode data: Copyright (c) 1991-2023 Unicode, Inc.,\n'
            '// Unicode License v3 (full text in THIRD_PARTY_NOTICES.md).\n' % unicodedata.unidata_version)
    f.write('static const uint32_t kCatRuns[] = {\n')
    for i,(s,c) in enumerate(runs):
        f.write('0x%x,' % ((s<<8)|c))
        if i%12==11: f.write('\n')
    f.write('};\n')
    f.write('static const uint32_t kLowerMap[] = {\n')
    for i,(s,l) in enumerate(lower):
        f.write('0x%x,' % ((s<<16)|l))
        if i%10==9: f.write('\n')
    f.write('};\n')
print(len(runs), len(lower))
