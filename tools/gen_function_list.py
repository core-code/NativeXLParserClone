# Regenerates src/excel_functions.inc from XLParser's web-demo resource ExcelBuiltinFunctionList-v139.txt
# (git: spreadsheetlab/XLParser, app/XLParser.Web/Resources/ExcelBuiltinFunctionList-v139.txt).
import sys
names = [l.strip() for l in open(sys.argv[1], encoding='utf-8-sig').read().replace('\r', '\n').split('\n') if l.strip()]
with open(sys.argv[2], 'w') as f:
    f.write('// This Source Code Form is subject to the terms of the Mozilla Public\n'
            '// License, v. 2.0. If a copy of the MPL was not distributed with this\n'
            '// file, You can obtain one at https://mozilla.org/MPL/2.0/.\n'
            '//\n'
            '// Generated by tools/gen_function_list.py. Excel built-in function list used by XLParser v1.3.9\n'
            '// (XLParser web demo resource ExcelBuiltinFunctionList-v139.txt, MPL 2.0), in original order.\n')
    f.write('static const char* const kExcelFunctions[] = {\n')
    for i, n in enumerate(names):
        f.write('"%s",' % n)
        if i % 8 == 7: f.write('\n')
    f.write('\n};\n')
